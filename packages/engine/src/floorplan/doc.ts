// Render the floor-plan model as a human-readable Markdown architecture doc with a
// Mermaid systems diagram. Written to `.factory/architecture.md` on each swarm run,
// so it shows up in the desktop Docs tab (which renders Markdown + Mermaid) and is a
// shareable, diff-able artifact — the deterministic, zero-cost companion to the
// interactive Floor Plan.
import { resolve } from "node:path";

import { writeFileAtomic } from "../fs-atomic.js";
import type { RepositoryModel } from "./types.js";

/** Strip characters that would break a Mermaid node label. */
function mermaidLabel(s: string): string {
  return s.replace(/["[\]{}|<>]/g, "").trim() || "node";
}

/** Render the model as Markdown (Mermaid diagram + per-system detail). */
export function renderArchitectureDoc(model: RepositoryModel): string {
  const systems = model.nodes.filter((n) => n.kind === "system");
  const lines: string[] = [];

  lines.push("# Architecture", "");
  lines.push(
    `_Generated by the Software Factory deep audit on ${model.generatedAt}._`,
    "",
  );
  lines.push(
    `${model.summary.systemCount} systems · ${model.summary.nodeCount} nodes · ${model.summary.edgeCount} connections`,
    "",
  );
  if (model.summary.partial) {
    lines.push("> ⚠️ Partial model — one or more areas failed to analyze.", "");
  }

  // System-level Mermaid diagram (kept to systems so it stays readable).
  const mid = new Map<string, string>();
  systems.forEach((s, i) => mid.set(s.id, `s${i}`));
  lines.push("```mermaid", "flowchart LR");
  for (const s of systems) {
    lines.push(`  ${mid.get(s.id)}["${mermaidLabel(s.title)}"]`);
  }
  for (const e of model.edges) {
    const from = mid.get(e.from);
    const to = mid.get(e.to);
    if (from && to) lines.push(`  ${from} -->|${e.kind}| ${to}`);
  }
  lines.push("```", "");

  // Per-system detail with its subsystems/features/APIs.
  for (const s of systems) {
    lines.push(`## ${s.title}`, "");
    if (s.summary) lines.push(s.summary, "");
    const children = model.nodes.filter((n) => n.parent === s.id);
    for (const c of children) {
      const tech = c.tech?.length ? ` _(${c.tech.join(", ")})_` : "";
      const summary = c.summary ? `: ${c.summary}` : "";
      lines.push(`- **${c.title}** — ${c.kind}${tech}${summary}`);
    }
    if (children.length > 0) lines.push("");
  }

  // The profile the swarm inferred (what the Profile tab offers to apply).
  const d = model.detected;
  const trueFlags = Object.entries(d.flags)
    .filter(([, v]) => v)
    .map(([k]) => k);
  lines.push("## Detected profile", "");
  lines.push(`- **type**: ${d.type ?? "(unknown)"}`);
  lines.push(`- **phase**: ${d.phase ?? "(unknown)"}`);
  lines.push(`- **stack**: ${d.stack.join(", ") || "(unknown)"}`);
  lines.push(`- **flags**: ${trueFlags.join(", ") || "(none)"}`);
  lines.push(`- **confidence**: ${Math.round(d.confidence * 100)}%`, "");

  return lines.join("\n");
}

/** Write the architecture doc to `.factory/architecture.md` (atomic). */
export async function saveArchitectureDoc(
  repoPath: string,
  model: RepositoryModel,
): Promise<void> {
  await writeFileAtomic(
    resolve(repoPath, ".factory", "architecture.md"),
    renderArchitectureDoc(model),
  );
}
