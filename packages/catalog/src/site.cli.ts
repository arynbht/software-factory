// `catalog:site` entrypoint. Renders every control to browsable Markdown under
// docs/catalog/ (one page per lane + an index) so the catalog is readable on GitHub.
// Run via `pnpm catalog:site`; CI checks the output is current.
import { mkdir, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import type { Control, FixConfig } from "./schema.js";
import { LANES } from "./taxonomy.js";
import { loadCatalog } from "./validate.js";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const repoRoot = resolve(root, "..", "..");
const outDir = resolve(repoRoot, "docs", "catalog");

const { controls } = await loadCatalog(resolve(root, "controls"));

/** Compile-time exhaustiveness guard: a new union member makes this a type error. */
function assertNever(value: never): never {
  throw new Error(`unhandled fix type: ${JSON.stringify(value)}`);
}

function fixSummary(fix: FixConfig | undefined): string {
  if (!fix) return "—";
  switch (fix.type) {
    case "template":
      return `template \`${fix.template}\``;
    case "merge-yaml":
    case "merge-json":
      return `${fix.type} \`${fix.file}\``;
    case "github-setting":
      return `github-setting \`${fix.setting}\``;
    case "command":
      return `command \`${fix.run}\``;
    case "claude":
      return `claude \`${fix.task}\``;
    default:
      // A future fix type must extend this switch rather than render "undefined".
      return assertNever(fix);
  }
}

function detectSummary(control: Control): string {
  return control.detect.map((d) => `\`${d.type}\``).join(", ");
}

function renderControl(control: Control): string {
  const refs = control.references
    .map(
      (r) => `  - [${r.name}](${r.url})${r.section ? ` — ${r.section}` : ""}`,
    )
    .join("\n");
  return [
    `### \`${control.id}\` — ${control.title}`,
    "",
    `- **phase**: ${control.phase} · **severity**: ${control.severity} · **effort**: ${control.effort ?? "—"}`,
    `- **detect**: ${detectSummary(control)} · **fix**: ${fixSummary(control.fix)}`,
    "",
    control.rationale.trim(),
    "",
    "References:",
    refs,
  ].join("\n");
}

const byLane = new Map<string, Control[]>();
for (const c of controls) {
  const arr = byLane.get(c.lane) ?? [];
  arr.push(c);
  byLane.set(c.lane, arr);
}

await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });

// One page per lane (only lanes that have controls).
const indexRows: string[] = [];
for (const lane of LANES) {
  const laneControls = (byLane.get(lane.key) ?? []).sort((a, b) =>
    a.id.localeCompare(b.id),
  );
  if (laneControls.length === 0) {
    indexRows.push(`| ${lane.title} | 0 | _(none yet)_ |`);
    continue;
  }
  const body = [
    `# ${lane.title}`,
    "",
    lane.description,
    "",
    `${laneControls.length} control(s).`,
    "",
    ...laneControls.map(renderControl),
    "",
  ].join("\n\n");
  await writeFile(resolve(outDir, `${lane.key}.md`), `${body}\n`, "utf8");
  indexRows.push(
    `| [${lane.title}](${lane.key}.md) | ${laneControls.length} | ${lane.description} |`,
  );
}

const index = [
  "# Control catalog",
  "",
  `${controls.length} controls across ${LANES.length} lanes. Generated by \`pnpm catalog:site\` — do not edit by hand.`,
  "",
  "| Lane | Controls | Description |",
  "| --- | --- | --- |",
  ...indexRows,
  "",
].join("\n");
await writeFile(resolve(outDir, "README.md"), index, "utf8");

console.log(
  `Rendered ${controls.length} controls to ${dirname(outDir)}/catalog/`,
);
